import { TransactionCanceledException } from '@aws-sdk/client-dynamodb';
import { BatchGetCommand, DynamoDBDocumentClient, GetCommand, QueryCommand, TransactWriteCommand } from '@aws-sdk/lib-dynamodb';
import { META_SK, ProductMetaItem, ProductMetaItemSchema, STOCK_SK, productPk } from './model';
import {
  CreateOrderRequest,
  IDEMPOTENCY_TTL_SECONDS,
  IdempotencyItemSchema,
  ORDER_SK_PREFIX,
  OrderItem,
  OrderItemSchema,
  idempSk,
  orderSk,
  requestHash,
  tenantPk,
} from './order-model';

/**
 * 訂單的讀寫（ADR-025）。每個方法都用「該租戶」的 DynamoDB client（租戶範圍憑證，ADR-024），
 * 所以即使這裡算錯 key，IAM 也只允許碰 TENANT#<自己>。
 * Order reads/writes. Every call uses the tenant's own client (tenant-scoped credentials), so even a wrong key
 * here can only ever reach TENANT#<own>.
 */

export type CreateOrderResult =
  | { readonly kind: 'created'; readonly order: OrderItem }
  | { readonly kind: 'replayed'; readonly order: OrderItem }
  | { readonly kind: 'idempotency_mismatch' }
  | { readonly kind: 'unknown_products'; readonly productIds: string[] }
  | { readonly kind: 'insufficient_stock'; readonly productIds: string[] }
  | { readonly kind: 'throttled' }
  | { readonly kind: 'busy' };

export interface CreateOrderInput {
  readonly tenantId: string;
  /** 下單者（JWT sub）/ Who placed the order. */
  readonly createdBy: string;
  readonly idempotencyKey: string;
  readonly request: CreateOrderRequest;
  /** o_<ULID>，由呼叫端產生（方便測試）/ Generated by the caller (testable). */
  readonly orderId: string;
  readonly now: Date;
}

export interface OrderPage {
  readonly orders: OrderItem[];
  readonly lastSk?: string;
}

/** 交易衝突時的重試次數 / Retries on TransactionConflict. */
const MAX_CONFLICT_RETRIES = 3;
const THROTTLE_CODES = new Set(['ThrottlingError', 'ProvisionedThroughputExceeded', 'RequestLimitExceeded']);
const THROTTLE_ERRORS = new Set(['ThrottlingException', 'ProvisionedThroughputExceededException', 'RequestLimitExceeded']);

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export class OrderRepo {
  constructor(
    /** 回傳該租戶專用的 client / Returns the client bound to the tenant's credentials. */
    private readonly forTenant: (tenantId: string) => DynamoDBDocumentClient,
    private readonly tableName: string,
    private readonly backoffMs: (attempt: number) => number = (a) => 25 * 2 ** a + Math.random() * 25,
  ) {}

  async createOrder(input: CreateOrderInput): Promise<CreateOrderResult> {
    const doc = this.forTenant(input.tenantId);
    const hash = requestHash(input.request);
    const nowSec = Math.floor(input.now.getTime() / 1000);

    // 1) 快速路徑：已經處理過 → 直接回原訂單（交易內的條件仍是最後防線）
    //    Fast path for replays; the transaction condition below is still the real guard.
    const prior = await this.replay(doc, input.tenantId, input.idempotencyKey, hash, nowSec);
    if (prior) return prior;

    // 2) 讀商品價格與狀態（伺服器端定價，不信任 client）/ Server-side pricing.
    const ids = input.request.items.map((i) => i.product_id);
    const metas = await this.getActiveMetas(doc, ids);
    const unknown = ids.filter((id) => !metas.has(id));
    if (unknown.length > 0) return { kind: 'unknown_products', productIds: unknown };

    const createdAt = input.now.toISOString();
    const lines = input.request.items.map((i) => {
      const meta = metas.get(i.product_id)!;
      return {
        product_id: i.product_id,
        name: meta.name,
        qty_kg: i.qty_kg,
        price_per_kg: meta.price_per_kg,
        line_total: meta.price_per_kg * i.qty_kg,
      };
    });
    const order: OrderItem = {
      pk: tenantPk(input.tenantId),
      sk: orderSk(input.orderId),
      entity: 'Order',
      order_id: input.orderId,
      tenant_id: input.tenantId,
      status: 'CREATED',
      // ORD-F-010：模擬付款，建立即視為已付款 / Mock payment: paid on creation.
      payment_status: 'PAID_MOCK',
      items: lines,
      total: lines.reduce((s, l) => s + l.line_total, 0),
      currency: 'TWD',
      created_by: input.createdBy,
      created_at: createdAt,
      idempotency_key: input.idempotencyKey,
    };

    // 3) 一個交易：冪等記錄 + 訂單 + 每個商品扣庫存（全部成功或全部失敗）
    //    One transaction: idempotency record + order + one stock reservation per product (all or nothing).
    const command = new TransactWriteCommand({
      TransactItems: [
        {
          Put: {
            TableName: this.tableName,
            Item: {
              pk: order.pk,
              sk: idempSk(input.idempotencyKey),
              entity: 'Idempotency',
              request_hash: hash,
              order_id: order.order_id,
              created_at: createdAt,
              expires_at: nowSec + IDEMPOTENCY_TTL_SECONDS,
            },
            // TTL 刪除會延遲 → 過期但還沒刪的記錄視同不存在 / TTL deletes lazily: treat expired records as absent.
            ConditionExpression: 'attribute_not_exists(pk) OR expires_at < :now',
            ExpressionAttributeValues: { ':now': nowSec },
          },
        },
        {
          Put: {
            TableName: this.tableName,
            Item: { ...order, gsi1pk: `STATUS#${order.status}`, gsi1sk: `${createdAt}#${order.order_id}`, updated_at: createdAt },
            ConditionExpression: 'attribute_not_exists(pk)',
          },
        },
        ...lines.map((l) => ({
          Update: {
            TableName: this.tableName,
            Key: { pk: productPk(l.product_id), sk: STOCK_SK },
            // 只碰 IAM 允許的庫存欄位（dynamodb:Attributes，ADR-024）/ Only the attributes IAM allows.
            UpdateExpression: 'SET #a = #a - :q, #r = #r + :q, #v = #v + :one, #u = :ts',
            ConditionExpression: 'attribute_exists(#pk) AND #a >= :q',
            ExpressionAttributeNames: {
              '#a': 'available_kg',
              '#r': 'reserved_kg',
              '#v': 'version',
              '#u': 'updated_at',
              '#pk': 'pk',
            },
            ExpressionAttributeValues: { ':q': l.qty_kg, ':one': 1, ':ts': createdAt },
          },
        })),
      ],
    });

    for (let attempt = 0; ; attempt++) {
      try {
        await doc.send(command);
        return { kind: 'created', order };
      } catch (err) {
        if (THROTTLE_ERRORS.has((err as Error).name)) return { kind: 'throttled' };
        if (!(err instanceof TransactionCanceledException)) throw err;
        const codes = (err.CancellationReasons ?? []).map((r) => r.Code ?? 'None');

        if (codes[0] === 'ConditionalCheckFailed') {
          // 另一個相同 key 的請求先完成了 / A concurrent request with the same key won.
          const winner = await this.replay(doc, input.tenantId, input.idempotencyKey, hash, nowSec);
          if (winner) return winner;
          throw new Error('Idempotency record conflict without a readable record');
        }
        if (codes[1] === 'ConditionalCheckFailed') throw new Error('Order id collision');
        const short = lines.filter((_, i) => codes[i + 2] === 'ConditionalCheckFailed').map((l) => l.product_id);
        if (short.length > 0) return { kind: 'insufficient_stock', productIds: short };
        if (codes.some((c) => THROTTLE_CODES.has(c))) return { kind: 'throttled' };
        if (codes.includes('TransactionConflict')) {
          if (attempt >= MAX_CONFLICT_RETRIES) return { kind: 'busy' };
          await sleep(this.backoffMs(attempt));
          continue;
        }
        throw err;
      }
    }
  }

  async getOrder(tenantId: string, orderId: string, consistent = false): Promise<OrderItem | undefined> {
    const out = await this.forTenant(tenantId).send(
      new GetCommand({
        TableName: this.tableName,
        Key: { pk: tenantPk(tenantId), sk: orderSk(orderId) },
        ConsistentRead: consistent,
      }),
    );
    const parsed = OrderItemSchema.safeParse(out.Item);
    return parsed.success && parsed.data.tenant_id === tenantId ? parsed.data : undefined;
  }

  /** 新的在前 / Newest first. `afterSk` 來自游標 / from the cursor. */
  async listOrders(tenantId: string, limit: number, afterSk?: string): Promise<OrderPage> {
    const pk = tenantPk(tenantId);
    const out = await this.forTenant(tenantId).send(
      new QueryCommand({
        TableName: this.tableName,
        KeyConditionExpression: 'pk = :pk AND begins_with(sk, :prefix)',
        ExpressionAttributeValues: { ':pk': pk, ':prefix': ORDER_SK_PREFIX },
        ScanIndexForward: false,
        Limit: limit,
        // pk 一律由已驗證的租戶組出，游標只決定 sk / pk always comes from the verified tenant.
        ExclusiveStartKey: afterSk ? { pk, sk: afterSk } : undefined,
      }),
    );
    const orders: OrderItem[] = [];
    for (const raw of out.Items ?? []) {
      const parsed = OrderItemSchema.safeParse(raw);
      if (parsed.success) orders.push(parsed.data);
    }
    const last = out.LastEvaluatedKey?.sk;
    return { orders, lastSk: typeof last === 'string' ? last : undefined };
  }

  /** 冪等記錄存在且未過期 → 同一請求回原訂單、不同請求回 mismatch / Replay or mismatch. */
  private async replay(
    doc: DynamoDBDocumentClient,
    tenantId: string,
    key: string,
    hash: string,
    nowSec: number,
  ): Promise<CreateOrderResult | undefined> {
    const out = await doc.send(
      new GetCommand({ TableName: this.tableName, Key: { pk: tenantPk(tenantId), sk: idempSk(key) }, ConsistentRead: true }),
    );
    const rec = IdempotencyItemSchema.safeParse(out.Item);
    if (!rec.success || rec.data.expires_at < nowSec) return undefined;
    if (rec.data.request_hash !== hash) return { kind: 'idempotency_mismatch' };
    const order = await this.getOrder(tenantId, rec.data.order_id, true);
    if (!order) throw new Error('Idempotency record points to a missing order');
    return { kind: 'replayed', order };
  }

  private async getActiveMetas(doc: DynamoDBDocumentClient, ids: readonly string[]): Promise<Map<string, ProductMetaItem>> {
    const result = new Map<string, ProductMetaItem>();
    let keys: Array<Record<string, unknown>> = ids.map((id) => ({ pk: productPk(id), sk: META_SK }));
    for (let attempt = 0; keys.length > 0 && attempt <= 3; attempt++) {
      const out = await doc.send(new BatchGetCommand({ RequestItems: { [this.tableName]: { Keys: keys } } }));
      for (const raw of out.Responses?.[this.tableName] ?? []) {
        const parsed = ProductMetaItemSchema.safeParse(raw);
        if (parsed.success && parsed.data.status === 'active' && parsed.data.currency === 'TWD') {
          result.set(parsed.data.id, parsed.data);
        }
      }
      keys = (out.UnprocessedKeys?.[this.tableName]?.Keys ?? []) as Array<Record<string, unknown>>;
      if (keys.length > 0) await sleep(this.backoffMs(attempt));
    }
    if (keys.length > 0) throw new Error(`BatchGetItem left ${keys.length} unprocessed keys`);
    return result;
  }
}
